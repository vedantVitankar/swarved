/// Corner radii, so no screen invents its own.
/// Every value is taken from the theme preview.
class AppShape {
  AppShape._();

  static const double button = 2; // sharp, tactile outlined buttons
  static const double thumbnail = 4; // small art in list rows
  static const double tile = 6; // folder tiles on Home
  static const double panel = 8; // mini player, Now Playing artwork
  static const double card = 12; // note and dedication cards
  static const double chip = 16; // filter chips
}
